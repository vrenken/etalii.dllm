// x [tokens][heads][head_dim] float, positions [tokens] int64, inv_freq [rotary_dim / 2] double.
inline Array rope(const Array& x, const Array& positions, const Array& inv_freq, std::size_t tokens,
                  std::size_t heads, std::size_t head_dim, bool interleaved, bool inverse) {
    const std::size_t rotary_dim = 2 * (inv_freq.bytes() / sizeof(double));
    detail::require(x.bytes() == tokens * heads * head_dim * sizeof(float), "rope: x does not match its shape");
    detail::require(positions.bytes() == tokens * sizeof(std::int64_t), "rope: one position per token");
    detail::require(rotary_dim <= head_dim, "rope: 2 * len(inv_freq) must not exceed head_dim");
    Runtime& runtime = Runtime::instance();
    auto lock = runtime.acquire();
    Array out(x.bytes());
    CUdeviceptr dx = x.pointer();
    CUdeviceptr dp = positions.pointer();
    CUdeviceptr df = inv_freq.pointer();
    CUdeviceptr dout = out.pointer();
    unsigned long long t = tokens;
    unsigned long long h = heads;
    unsigned long long d = head_dim;
    unsigned long long rd = rotary_dim;
    int inter = interleaved ? 1 : 0;
    int inv = inverse ? 1 : 0;
    void* arguments[] = {&dx, &dp, &df, &dout, &t, &h, &d, &rd, &inter, &inv};
    const std::size_t work = tokens * heads * (rotary_dim / 2 + head_dim - rotary_dim);
    runtime.launch(Runtime::kRope, detail::blocks_for(work), 1, detail::kBlock, arguments);
    return out;
}

// Rows of scores kept on the device at once; rows are independent, so the slicing never changes a result.
constexpr std::size_t kAttentionScratchDoubles = std::size_t(1) << 23;  // 64 MiB

// q [q_len][q_heads][head_dim], k [>= kv_len][kv_heads][head_dim], v [>= kv_len][kv_heads][value_dim]: only the
// first kv_len keys and values are read.
inline Array attention(const Array& q, const Array& k, const Array& v, std::size_t q_len, std::size_t kv_len,
                       std::size_t q_heads, std::size_t kv_heads, std::size_t head_dim, std::size_t value_dim,
                       double scale, bool causal, std::size_t q_offset, std::size_t window = 0) {
    detail::require(kv_heads > 0 && q_heads % kv_heads == 0, "q_heads must be a multiple of kv_heads");
    detail::require(q.bytes() == q_len * q_heads * head_dim * sizeof(float), "attention: q does not match its shape");
    detail::require(k.bytes() >= kv_len * kv_heads * head_dim * sizeof(float), "attention: k is too short");
    detail::require(v.bytes() >= kv_len * kv_heads * value_dim * sizeof(float), "attention: v is too short");
    Runtime& runtime = Runtime::instance();
    auto lock = runtime.acquire();
    const std::size_t rows = q_len * q_heads;
    Array out(rows * value_dim * sizeof(float));
    const std::size_t keys = std::max<std::size_t>(kv_len, 1);
    const std::size_t per_launch = std::max<std::size_t>(1, std::min(detail::kMaxGridY, kAttentionScratchDoubles / keys));
    Array scratch(std::min(per_launch, std::max<std::size_t>(rows, 1)) * keys * sizeof(double));
    CUdeviceptr dq = q.pointer();
    CUdeviceptr dk = k.pointer();
    CUdeviceptr dv = v.pointer();
    CUdeviceptr dout = out.pointer();
    CUdeviceptr dscratch = scratch.pointer();
    unsigned long long kl = kv_len;
    unsigned long long qh = q_heads;
    unsigned long long kh = kv_heads;
    unsigned long long hd = head_dim;
    unsigned long long vd = value_dim;
    int c = causal ? 1 : 0;
    unsigned long long offset = q_offset;
    unsigned long long w = window;
    for (std::size_t row0 = 0; row0 < rows; row0 += per_launch) {
        unsigned long long first = row0;
        void* arguments[] = {&dq, &dk, &dv, &dout, &dscratch, &first, &kl, &qh, &kh, &hd, &vd, &scale, &c, &offset, &w};
        runtime.launch(Runtime::kAttention, static_cast<unsigned>(std::min(per_launch, rows - row0)), 1,
                       detail::kBlock, arguments);
    }
    return out;
}

