// Headers the device code includes, as tiny stand-ins (NVRTC has no C++ standard library). math.hpp only needs
// size_t, the fixed-width integers, a byte copy and three double constants.
inline const char* const kShimNames[] = {"cmath", "cstddef", "cstdint", "cstring", "limits", "stdexcept"};
inline const char* const kShimSources[] = {
    "#pragma once\n",
    "#pragma once\nnamespace std { typedef unsigned long long size_t; }\n",
    "#pragma once\nnamespace std { typedef signed char int8_t; typedef int int32_t; typedef long long int64_t;\n"
    "typedef unsigned char uint8_t; typedef unsigned int uint32_t; typedef unsigned long long uint64_t; }\n",
    "#pragma once\nnamespace std { inline void* memcpy(void* d, const void* s, unsigned long long n) {\n"
    "unsigned char* o = static_cast<unsigned char*>(d); const unsigned char* i = static_cast<const unsigned char*>(s);\n"
    "for (unsigned long long k = 0; k < n; ++k) { o[k] = i[k]; } return d; } }\n",
    "#pragma once\nnamespace std { template <class T> struct numeric_limits;\n"
    "template <> struct numeric_limits<double> {\n"
    "static double infinity() { return __longlong_as_double(0x7ff0000000000000LL); }\n"
    "static double quiet_NaN() { return __longlong_as_double(0x7ff8000000000000LL); }\n"
    "static double min() { return __longlong_as_double(0x0010000000000000LL); } }; }\n",
    "#pragma once\n",
};

class Library {
public:
    Library() = default;
    Library(const Library&) = delete;
    Library& operator=(const Library&) = delete;

    bool open(const std::string& path) {
#ifdef _WIN32
        // With a full path, the DLL's own directory is searched for its dependencies (nvrtc-builtins).
        const DWORD flags = path.find_first_of("\\/") != std::string::npos ? LOAD_WITH_ALTERED_SEARCH_PATH : 0;
        handle_ = reinterpret_cast<void*>(LoadLibraryExA(path.c_str(), nullptr, flags));
#else
        handle_ = dlopen(path.c_str(), RTLD_NOW | RTLD_LOCAL);
#endif
        return handle_ != nullptr;
    }

    template <typename F>
    F symbol(const char* name) const {
#ifdef _WIN32
        void* address = reinterpret_cast<void*>(GetProcAddress(static_cast<HMODULE>(handle_), name));
#else
        void* address = dlsym(handle_, name);
#endif
        if (address == nullptr) {
            throw std::runtime_error(std::string("CUDA: missing symbol ") + name);
        }
        return reinterpret_cast<F>(address);
    }

private:
    void* handle_ = nullptr;  // never closed: the process keeps the driver loaded
};

