// The CUDA backend: runs the kernels of cpp/cuda/kernels.cu on an NVIDIA GPU with the CPU's bits.
//
// Nothing CUDA is needed to build the extension. At run time the CUDA driver (nvcuda.dll / libcuda.so.1, part of
// the NVIDIA driver) and NVRTC (the CUDA runtime compiler; any CUDA 11.2+ copy, for example the nvidia-cuda-nvrtc
// wheel, a CUDA toolkit or PyTorch's) are loaded dynamically, and kernels.cu plus math.hpp, embedded in the
// extension by CMake, are compiled for the GPU that is present with --fmad=false (no multiply-add contraction),
// IEEE division and square root, and no flush-to-zero. The Python layer (etalii_dllm.cuda) finds NVRTC and calls
// initialize().
//
// Weights, activations and the KV cache live on the device as Arrays. Operations queue their kernels on one stream
// without waiting; only a download waits, for the work that produces its data. Callers on several threads take
// turns queueing, and since no kernel's result depends on what else is queued, concurrency cannot change a bit.
